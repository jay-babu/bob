package gen

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

const header = "// Code generated by bob next. DO NOT EDIT.\n\n"
const runtimePath = "github.com/stephenafamo/bob/next"
const manifestFile = ".bob-next-manifest.json"

type Report struct{ Written, Unchanged, Removed, Bytes int }

// Generate renders and validates every file before touching the output. It
// preserves unchanged files and removes only files owned by its prior manifest.
// An interrupted run is repaired by rerunning; publication is not transactional.
func Generate(s Schema, config Config) (Report, error) {
	var report Report
	if err := s.Validate(); err != nil {
		return report, err
	}
	if config.Directory == "" || config.ImportPath == "" || strings.ContainsAny(config.ImportPath, "\"\n\r\\") {
		return report, fmt.Errorf("output directory and valid import path are required")
	}
	files := map[string][]byte{}
	tables := map[string]Table{}
	for _, t := range s.Tables {
		tables[t.Key] = t
		code, err := renderTable(t)
		if err != nil {
			return report, err
		}
		files[t.Package+"/table.bob.go"] = code
	}
	for _, name := range config.Relations {
		found := false
		for _, r := range s.Relations {
			if r.Name != name {
				continue
			}
			found = true
			from, to := tables[r.From], tables[r.To]
			var b strings.Builder
			fmt.Fprintf(&b, "%spackage %s\nimport (\n next %q\n from %q\n", header, r.Name, runtimePath, config.ImportPath+"/"+from.Package)
			target := "from"
			if r.From != r.To {
				fmt.Fprintf(&b, " to %q\n", config.ImportPath+"/"+to.Package)
				target = "to"
			}
			fmt.Fprintf(&b, ")\nvar Relation = next.Relation{From: from.Table, To: %s.Table, FromColumns: %#v, ToColumns: %#v}\n", target, r.FromColumns, r.ToColumns)
			code, err := format.Source([]byte(b.String()))
			if err != nil {
				return report, err
			}
			files["relations/"+r.Name+"/relation.bob.go"] = code
		}
		if !found {
			return report, fmt.Errorf("requested relationship %s does not exist", name)
		}
	}
	// Metadata ordering is canonical; column and composite-key ordering is semantic.
	s.Tables = slices.Clone(s.Tables)
	for i := range s.Tables {
		s.Tables[i].Imports = slices.Clone(s.Tables[i].Imports)
		slices.Sort(s.Tables[i].Imports)
		s.Tables[i].Imports = slices.Compact(s.Tables[i].Imports)
	}
	slices.SortFunc(s.Tables, func(a, b Table) int { return strings.Compare(a.Key, b.Key) })
	s.Relations = slices.Clone(s.Relations)
	slices.SortFunc(s.Relations, func(a, b Relation) int { return strings.Compare(a.Name, b.Name) })
	metadata, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return report, err
	}
	files["schema.json"] = append(metadata, '\n')
	old := map[string]string{}
	manifestPath := filepath.Join(config.Directory, manifestFile)
	if data, readErr := os.ReadFile(manifestPath); readErr == nil {
		if err := json.Unmarshal(data, &old); err != nil {
			return report, fmt.Errorf("invalid generation manifest: %w", err)
		}
	} else if !os.IsNotExist(readErr) {
		return report, readErr
	}
	paths := make([]string, 0, len(files))
	for path := range files {
		paths = append(paths, path)
	}
	slices.Sort(paths)
	// Check ownership before writing any files, including stale-file deletions.
	for path, expected := range old {
		if !safePath(path) {
			return report, fmt.Errorf("unsafe path in generation manifest")
		}
		actual, err := os.ReadFile(filepath.Join(config.Directory, path))
		if err != nil && !os.IsNotExist(err) {
			return report, err
		}
		if err == nil && digest(actual) != expected {
			// A prior interrupted run may already have published this exact output.
			if desired, exists := files[path]; !exists || !bytes.Equal(actual, desired) {
				return report, fmt.Errorf("generated file %s was edited; refusing to overwrite", path)
			}
		}
	}
	for _, path := range paths {
		if _, owned := old[path]; owned {
			continue
		}
		actual, err := os.ReadFile(filepath.Join(config.Directory, path))
		if err == nil && !bytes.Equal(actual, files[path]) {
			return report, fmt.Errorf("output %s is not owned by this generator", path)
		}
		if err != nil && !os.IsNotExist(err) {
			return report, err
		}
	}
	manifest := map[string]string{}
	for _, path := range paths {
		content := files[path]
		report.Bytes += len(content)
		manifest[path] = digest(content)
		full := filepath.Join(config.Directory, path)
		current, _ := os.ReadFile(full)
		if bytes.Equal(current, content) {
			report.Unchanged++
			continue
		}
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return report, err
		}
		if err := atomicWrite(full, content); err != nil {
			return report, err
		}
		report.Written++
	}
	for path := range old {
		if _, exists := files[path]; exists {
			continue
		}
		if err := os.Remove(filepath.Join(config.Directory, path)); err != nil && !os.IsNotExist(err) {
			return report, err
		}
		report.Removed++
	}
	manifestBytes, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return report, err
	}
	previous, _ := os.ReadFile(manifestPath)
	if !bytes.Equal(previous, manifestBytes) {
		if err := atomicWrite(manifestPath, manifestBytes); err != nil {
			return report, err
		}
	}
	return report, nil
}

func digest(data []byte) string { return fmt.Sprintf("%x", sha256.Sum256(data)) }

func safePath(path string) bool {
	return !filepath.IsAbs(path) && filepath.Clean(path) == path && path != ".." && !strings.HasPrefix(path, ".."+string(filepath.Separator))
}
func atomicWrite(path string, data []byte) error {
	f, err := os.CreateTemp(filepath.Dir(path), ".bob-next-*")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name())
	if _, err = f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err = f.Chmod(0o644); err != nil {
		f.Close()
		return err
	}
	if err = f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), path)
}

func renderTable(t Table) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "%spackage %s\nimport (\n next %q\n", header, t.Package, runtimePath)
	nullable := false
	for _, c := range t.Info.Columns {
		nullable = nullable || c.Nullable
	}
	imports := slices.Clone(t.Imports)
	slices.Sort(imports)
	imports = slices.Compact(imports)
	sqlAlias, hasSQL := "sql", false
	for _, imp := range imports {
		parts := strings.Fields(imp)
		if len(parts) == 0 {
			return nil, fmt.Errorf("empty import for %s", t.Key)
		}
		path, err := strconv.Unquote(parts[len(parts)-1])
		if err != nil {
			return nil, fmt.Errorf("invalid import for %s", t.Key)
		}
		if path == "database/sql" {
			if hasSQL {
				return nil, fmt.Errorf("repeated database/sql import for %s", t.Key)
			}
			hasSQL = true
			if len(parts) == 2 {
				sqlAlias = parts[0]
			}
			if nullable && (sqlAlias == "_" || sqlAlias == ".") {
				return nil, fmt.Errorf("nullable columns need a named database/sql import")
			}
		}
	}
	if nullable && !hasSQL {
		b.WriteString(" \"database/sql\"\n")
	}
	for _, imp := range imports {
		fmt.Fprintf(&b, " %s\n", imp)
	}
	b.WriteString(")\ntype Row struct {\n")
	for i, c := range t.Columns {
		typ := c.GoType
		if t.Info.Columns[i].Nullable {
			typ = sqlAlias + ".Null[" + typ + "]"
		}
		fmt.Fprintf(&b, " %s %s\n", c.GoName, typ)
	}
	b.WriteString("}\nvar Table = next.DefineTable(next.TableInfo{\n")
	fmt.Fprintf(&b, "Schema:%q,Name:%q,PrimaryKey:%#v,UniqueKeys:%#v,Columns:[]next.ColumnInfo{\n", t.Info.Schema, t.Info.Name, t.Info.PrimaryKey, t.Info.UniqueKeys)
	for _, c := range t.Info.Columns {
		fmt.Fprintf(&b, "{Name:%q,DBType:%q,Nullable:%t,HasDefault:%t,Generated:%t},\n", c.Name, c.DBType, c.Nullable, c.HasDefault, c.Generated)
	}
	b.WriteString("}})\ntype Columns struct { Ref next.Ref\n")
	for i, c := range t.Columns {
		typ := "Column"
		if t.Info.Columns[i].Generated {
			typ = "Expr"
		}
		fmt.Fprintf(&b, " %s next.%s[%s]\n", c.GoName, typ, c.GoType)
	}
	b.WriteString("}\nfunc As(alias string) Columns { r := Table.As(alias); return Columns{Ref:r,\n")
	for i, c := range t.Columns {
		suffix := ""
		if t.Info.Columns[i].Generated {
			suffix = ".Expr()"
		}
		fmt.Fprintf(&b, "%s:next.Field[%s](r,%q)%s,\n", c.GoName, c.GoType, c.Name, suffix)
	}
	b.WriteString("}}\nfunc (c Columns) Projection() next.Projection[Row] {return next.Projection[Row]{Columns:[]next.Selection{\n")
	for _, c := range t.Columns {
		fmt.Fprintf(&b, "c.%s.Select(%q),\n", c.GoName, c.Name)
	}
	b.WriteString("},Scan:func(s next.Scanner)(Row,error){ var v Row; err:=s.Scan(")
	for _, c := range t.Columns {
		fmt.Fprintf(&b, "&v.%s,", c.GoName)
	}
	b.WriteString(");return v,err}}}\n")
	for _, kind := range []string{"Insert", "Update"} {
		fmt.Fprintf(&b, "type %s struct {\n", kind)
		for i, c := range t.Columns {
			info := t.Info.Columns[i]
			if info.Generated {
				continue
			}
			typ := c.GoType
			if info.Nullable {
				typ = "next.NullableInput[" + typ + "]"
			} else if kind == "Update" || info.HasDefault {
				typ = "next.Input[" + typ + "]"
			}
			fmt.Fprintf(&b, " %s %s\n", c.GoName, typ)
		}
		fmt.Fprintf(&b, "}\nfunc(v %s) Assignments(c Columns) []next.Assignment {return []next.Assignment{\n", kind)
		for i, c := range t.Columns {
			info := t.Info.Columns[i]
			if info.Generated {
				continue
			}
			method := "Assign"
			if info.Nullable {
				method = "AssignNullable"
			} else if kind == "Insert" && !info.HasDefault {
				method = "Set"
			}
			fmt.Fprintf(&b, "c.%s.%s(v.%s),\n", c.GoName, method, c.GoName)
		}
		b.WriteString("}}\n")
	}
	code, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("render %s: %w", t.Key, err)
	}
	return code, nil
}

// Import returns a quoted Go import path suitable for Table.Imports.
func Import(path string) string { return strconv.Quote(path) }
